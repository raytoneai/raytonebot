import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
const context=await browser.newContext({viewport:{width:1280,height:900},reducedMotion:'reduce'});
const page=await context.newPage();
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
const row=name=>page.locator('.shell-agent-row').filter({has:page.locator('.shell-agent-name',{hasText:new RegExp(`^${name}$`)})});
const dialog=()=>page.getByRole('dialog');
const close=()=>dialog().getByRole('button',{name:'取消',exact:true}).click();
const checks=[];
try {
 await page.goto('http://127.0.0.1:5188/');
 await page.getByRole('button',{name:'创建 Bot',exact:true}).click();
 assert.equal(await dialog().getByLabel('名字',{exact:true}).inputValue(),'');
 assert.equal(await dialog().getByRole('button',{name:'创建 Bot',exact:true}).isDisabled(),true);
 await dialog().getByLabel('名字',{exact:true}).fill('Muse');
 await dialog().locator('fieldset').filter({has:page.locator('legend',{hasText:'头发',exact:true})}).getByRole('button',{name:'双丸子',exact:true}).click();
 await dialog().getByRole('button',{name:'创建 Bot',exact:true}).click();
 await row('Muse').waitFor();
 assert.equal(await page.locator('.shell-header-name').innerText(),'Muse');
 assert.equal(await page.locator('.shell-agent[data-active="true"] .shell-agent-name').innerText(),'Muse');
 const museId=await page.locator('.preview-frame').getAttribute('data-conversation-id');
 await page.locator('textarea').fill('Muse 独立草稿');
 await page.waitForTimeout(450);
 await row('Raer').locator('.shell-agent').click();
 assert.notEqual(await page.locator('.preview-frame').getAttribute('data-conversation-id'),museId);
 assert.equal(await page.locator('textarea').inputValue(),'');
 await page.locator('textarea').fill('Raer 独立草稿');
 await page.waitForTimeout(450);
 await page.locator('.session-list').evaluate(el=>{el.scrollTop=el.scrollHeight;});
 await page.getByRole('button',{name:'Muse 独立草稿',exact:true}).click();
 assert.equal(await page.locator('.shell-header-name').innerText(),'Muse');
 assert.equal(await page.locator('textarea').inputValue(),'Muse 独立草稿');
 checks.push('Create Pi Bot; separate conversation ID, drafts, history group and active header');
 for (const name of ['Raer','Tonny','Bob','Muse']) {
   await row(name).locator('.raytone-avatar').click({button:'right'});
   assert.equal(await dialog().getByLabel('名字',{exact:true}).inputValue(),name);
   assert.equal(await dialog().locator('select').isDisabled(),true);
   await dialog().getByLabel('名字',{exact:true}).fill('取消不应用');
   await close();
   await row(name).waitFor();
 }
 checks.push('All three defaults and custom Bot share editor; cancel preserves identity');
 await row('Muse').locator('.shell-agent').focus();
 await page.keyboard.press('Shift+F10');
 await dialog().getByLabel('名字',{exact:true}).fill('Muse II');
 await dialog().getByRole('button',{name:'保存',exact:true}).click();
 await row('Muse II').waitFor();
 assert.equal(await page.locator('.shell-header-name').innerText(),'Muse II');
 await page.reload();
 await row('Muse II').waitFor();
 await page.locator('.session-list').evaluate(el=>{el.scrollTop=el.scrollHeight;});
 const museGroup=page.locator('.session-bot-toggle').filter({has:page.locator('.session-bot-name',{hasText:'Muse II'})});
 if(await museGroup.getAttribute('aria-expanded')==='false') await museGroup.click();
 await page.locator('.session-list').evaluate(el=>{el.scrollTop=el.scrollHeight;});
 await page.getByRole('button',{name:'Muse 独立草稿',exact:true}).click();
 assert.equal(await page.locator('.shell-header-name').innerText(),'Muse II');
 assert.equal(await page.locator('textarea').inputValue(),'Muse 独立草稿');
 checks.push('Keyboard edit, rename, refreshed profile and conversation ownership');
 await page.getByRole('button',{name:'设置',exact:true}).click();
 assert.equal(await dialog().getByRole('button',{name:'Bot 头像',exact:true}).count(),0);
 await dialog().locator('.settings-close').click();
 checks.push('Settings has no Bot editor');
 await row('Raer').locator('.raytone-avatar').click({button:'right'});
 await dialog().getByLabel('名字',{exact:true}).fill('小蕾');
 await dialog().getByRole('button',{name:'保存',exact:true}).click();
 await row('小蕾').waitFor();
 await page.screenshot({path:'output/bot-editor/created-desktop.png'});
 await row('Muse II').locator('.raytone-avatar').click({button:'right'});
 await page.screenshot({path:'output/bot-editor/edit-desktop.png'});
 // Simulate browser quota failure only in this isolated test context.
 await page.evaluate(()=>{window.originalSetItem=Storage.prototype.setItem;Storage.prototype.setItem=function(k,v){if(k==='raytone.bot-profiles.v1')throw new DOMException('Quota exceeded','QuotaExceededError');return window.originalSetItem.call(this,k,v);};});
 await dialog().getByLabel('名字',{exact:true}).fill('保留失败草稿');
 await dialog().getByRole('button',{name:'保存',exact:true}).click();
 assert.match(await dialog().getByRole('alert').innerText(),/保存失败/);
 assert.equal(await dialog().getByLabel('名字',{exact:true}).inputValue(),'保留失败草稿');
 await page.evaluate(()=>{Storage.prototype.setItem=window.originalSetItem;});
 await close();
 checks.push('Quota failure is visible, keeps draft and leaves saved Bot intact');
 await page.setViewportSize({width:390,height:844});
 await page.locator('.preview-rail-float[data-side="left"]').click();
 await row('Muse II').getByRole('button',{name:'编辑 Muse II',exact:true}).click();
 assert.equal(await dialog().getByLabel('名字',{exact:true}).inputValue(),'Muse II');
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 const box=await dialog().getByRole('button',{name:'保存',exact:true}).boundingBox();
 assert.ok(box.y+box.height<=844);
 await page.screenshot({path:'output/bot-editor/edit-mobile.png'});
 await close();
 await page.getByRole('button',{name:'创建 Bot',exact:true}).click();
 await page.screenshot({path:'output/bot-editor/create-mobile.png'});
 await close();
 checks.push('390px Logo create + edit button, no overflow, fixed save/cancel reachable');
 assert.deepEqual(errors,[]);
 await writeFile('output/bot-editor/checks.json',JSON.stringify({checks,errors},null,2));
 console.log(JSON.stringify({checks,errors},null,2));
} catch(error) { await page.screenshot({path:'output/bot-editor/failure.png'}); console.log((await page.locator('body').innerText()).slice(0,3000)); throw error; } finally { await browser.close(); }
